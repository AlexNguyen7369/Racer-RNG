# Writes src/shared/BiomeMeshAssets.luau from the Studio MCP upload_image result (JSON on stdin:
# {"http://.../<Biome>_<Prop>.png": "rbxassetid://..."}). Re-run after re-baking the textures.
import json, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ids = {re.sub(r"\.png$", "", url.rsplit("/", 1)[-1]): asset for url, asset in json.load(sys.stdin).items()}
lines = [
    "--!nonstrict",
    '-- Uploaded textures of the baked CC0 biome props (docs/BIOME_DRESSING_SPEC.md "Assets"), keyed "<Biome>_<Prop>".',
    "-- Geometry is data in Shared/BiomeMeshData; Client/BiomeMeshes builds the meshes. Generated by",
    "-- blender/biomes/write_texture_ids.py; re-upload after re-baking.",
    "return {",
] + [f'\t{k} = "{ids[k]}",' for k in sorted(ids)] + ["}"]
open(os.path.join(root, "src", "shared", "BiomeMeshAssets.luau"), "w").write("\n".join(lines) + "\n")
print(len(ids), "texture ids written")
